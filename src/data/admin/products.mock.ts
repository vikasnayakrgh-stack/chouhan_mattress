const img = (id: string, seed: string, alt: string, pos: number, thumb = false) => ({
  id,
  url: `https://picsum.photos/seed/${seed}/800/600`,
  alt,
  position: pos,
  isThumbnail: thumb,
})

function variant(
  productId: string,
  sku: string,
  optionValues: Record<string, string>,
  mrp: number,
  sellingPrice: number,
  stock: number,
  dimensions?: string,
  lowStockThreshold = 10
): ProductVariant {
  return {
    id: `var-${sku.toLowerCase()}`,
    productId,
    sku,
    optionValues,
    dimensions,
    mrp,
    sellingPrice,
    discountPercent: Math.round(((mrp - sellingPrice) / mrp) * 100),
    stock,
    lowStockThreshold,
    status: 'active',
  }
}

